export const RTL_LANGS = ['ar'];
export function isRTL(lang) { return RTL_LANGS.includes(lang); }

// --- RTL style helpers -------------------------------------------------------
// We deliberately do NOT use I18nManager.forceRTL: it needs a full native app
// restart to take effect, which is unreliable in Expo Go and would strand the
// user mid-session. Instead each screen mirrors itself with these helpers, which
// is instant and reversible when the language changes.
export const rtlText = (rtl) => (rtl ? { textAlign: 'right', writingDirection: 'rtl' } : null);
export const rtlRow = (rtl) => (rtl ? { flexDirection: 'row-reverse' } : null);
export const rtlAlign = (rtl) => (rtl ? { alignItems: 'flex-end' } : null);
// Mirror a directional icon name (chevrons/arrows) for RTL.
export function rtlIcon(name, rtl) {
  if (!rtl) return name;
  if (name.includes('forward')) return name.replace('forward', 'back');
  if (name.includes('back')) return name.replace('back', 'forward');
  return name;
}
export function langName(code) { const l = LANGUAGES.find(x => x.code === code); return l ? l.native : 'English'; }

